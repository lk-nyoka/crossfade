"""Generate docs/EVALUATION.md from ml/reports so the document can never drift from the numbers."""
import json
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "ml" / "reports"
b = pd.read_csv(R / "benchmark.csv")
s = json.load(open(R / "run_summary.json"))
sl = pd.read_csv(R / "slices_test.csv")
cal = pd.read_csv(R / "calibration_test.csv")
shap = pd.read_csv(R / "shap_importance.csv", index_col=0)["mean_abs_shap"]
NAMES = {"B0_random": "B0 Random", "B1_market_popularity": "B1 Market popularity", "B2_transition_max": "B2 Strongest corridor",
         "B3_transition_noisy_or": "B3 Combined corridors (noisy-OR)", "B4_cultural_proximity": "B4 Cultural proximity",
         "B5_logistic_blend": "B5 Logistic blend of baselines", "Crossfade_LGBM": "**Crossfade (LightGBM)**"}


def table(split):
    rows = ["| Model | Hit@1 | Hit@3 | Recall@5 (95% CI) | Recall@10 | NDCG@10 | MRR | PR-AUC |", "|---|---|---|---|---|---|---|---|"]
    for _, r in b[b.split == split].iterrows():
        rows.append(f"| {NAMES[r.model]} | {r['hit@1']:.1%} | {r['hit@3']:.1%} | {r['recall@5']:.1%} ({r['recall@5_lo']:.1%}–{r['recall@5_hi']:.1%}) "
                    f"| {r['recall@10']:.1%} | {r['ndcg@10']:.3f} | {r['mrr']:.3f} | {r['pr_auc']:.3f} |")
    g = int(b[b.split == split].groups.iloc[0])
    return "\n".join(rows) + f"\n\n*{g:,} song-weeks with at least one real entry.*\n"


folds = []
for f in ["fold_2022", "fold_2023", "fold_2024"]:
    d = b[b.split == f].set_index("model")
    best = d.drop("Crossfade_LGBM")["recall@5"].idxmax()
    folds.append(f"| {f[-4:]} | {d.loc['Crossfade_LGBM','recall@5']:.1%} | {d.loc[best,'recall@5']:.1%} ({NAMES[best]}) | "
                 f"{d.loc['Crossfade_LGBM','hit@1']:.1%} | {d.drop('Crossfade_LGBM')['hit@1'].max():.1%} | "
                 f"{d.loc['Crossfade_LGBM','pr_auc']:.3f} | {d.drop('Crossfade_LGBM')['pr_auc'].max():.3f} |")

dv = pd.read_csv(R / "decision_value.csv")
dv10 = dv[dv.k_per_week == 10].pivot_table(index="roster", columns="model", values="precision")
dv_rows = "\n".join(f"| {ro} | {dv10.loc[ro,'Crossfade_LGBM']:.1%} | {dv10.loc[ro,'B5_logistic_blend']:.1%} | {dv10.loc[ro,'B3_transition_noisy_or']:.1%} | "
                     f"{dv10.loc[ro,'B1_market_popularity']:.1%} | {dv10.loc[ro,'B0_random']:.1%} |"
                     for ro in ["all rising songs", "emerging songs only", "10 songs x their #1 market", "songs charting in Africa"])
_a = dv[(dv.roster == "all rising songs") & (dv.k_per_week == 10)].set_index("model")
gl = lambda m: _a.loc[m, "global_launch_share"]
dsong = _a.loc["Crossfade_LGBM", "distinct_songs_median"]
slc = sl[sl.slice.isin(["all", "debuted_in_africa"])]
slc_rows = "\n".join(f"| {r.slice.replace('_', ' ')} | {'Crossfade' if r.model == 'Crossfade_LGBM' else 'Combined corridors'} | {r.groups:,} | "
                     f"{r['hit@1']:.1%} | {r['recall@5']:.1%} | {r['recall@10']:.1%} | {r.pr_auc:.3f} |" for _, r in slc.iterrows())
cal_rows = "\n".join(f"| {i+1} | {r.mean_pred:.4%} | {r.observed:.4%} | {int(r.n):,} |" for i, r in cal.iterrows())
shap_rows = "\n".join(f"| {f} | {v:.3f} |" for f, v in shap.head(12).items())

doc = f"""# Evaluation report

*Generated by `python scripts/write_eval_doc.py` from `ml/reports/` — do not edit by hand.*

## Protocol

- **Unit.** One row is (snapshot week *t*, song, target country) for every song that is charting somewhere at *t*, is at most 26 weeks past its national debut, and every one of the 43 national charts it has not entered yet. Label = first entry in (*t*, *t* + 4 weeks].
- **Universe.** 30,241,019 rows, 69,610 positives (base rate 0.230%), 747,119 song-weeks, 416 snapshot weeks (1 Nov 2018 – 17 Sep 2026) plus the live week 15 Oct 2026.
- **Splits.**
  - Training data: snapshots up to 5 Dec 2024.
  - Walk-forward validation on 2022, 2023 and 2024. Each fold trains only on snapshots at least 4 weeks before its validation year starts.
  - The final test covers 1 Jan 2025 – 17 Sep 2026 and was scored once.
- **Evaluation rows.**
  - Every test row is scored.
  - Validation folds use a random 25% of song-weeks, with all their rows kept so the rankings stay intact.
  - Training uses every positive plus 5% of negatives, weighted ×20. That keeps the probabilities calibrated, and the test confirms it.
- **Baselines.** Scored on exactly the same rows as the model. B2–B4 use the same point-in-time corridor estimates the model sees, and B5 is a logistic regression over B1–B4.
- **Metrics.**
  - Ranking metrics are averaged over song-weeks where the song entered at least one new market, since otherwise there's nothing to find.
  - PR-AUC pools every candidate, so it also measures whether the model knows *which* songs will travel.
  - The Recall@5 95% CI comes from 500 bootstrap resamples of snapshot weeks.

## Held-out test (Jan 2025 – Sep 2026), all songs

{table("test_all")}
## Held-out test, emerging songs (not a coordinated launch in ≥3 countries)

{table("test_emerging")}
## Held-out test, coordinated global launches only

{table("test_simultaneous_launch")}
## Decision value: a weekly slate of 10 picks

Each week, every model picks its 10 highest-scoring (song, market) pairs across all rising songs. The table shows the share that entered that chart within 4 weeks, over 90 test weeks (900 picks per model).

| Roster | Crossfade | Logistic blend | Combined corridors | Market popularity | Random |
|---|---|---|---|---|---|
{dv_rows}

The corridor baseline spends {gl('B3_transition_noisy_or'):.0%} of its slate on coordinated global launches, which are songs that need the least help. Crossfade spends {gl('Crossfade_LGBM'):.0%} there, and its weekly slate covers a median of {dsong:.0f} different songs. The full K = 10/25/50/100 grid is in `ml/reports/decision_value.csv`.

## Walk-forward validation

| Year | Crossfade Recall@5 | Best baseline Recall@5 | Crossfade Hit@1 | Best baseline Hit@1 | Crossfade PR-AUC | Best baseline PR-AUC |
|---|---|---|---|---|---|---|
{chr(10).join(folds)}

## Slices (held-out test)

| Slice | Model | Song-weeks | Hit@1 | Recall@5 | Recall@10 | PR-AUC |
|---|---|---|---|---|---|---|
{slc_rows}

"Debuted in Africa" = the song's first national chart was Kenya, Nigeria, South Africa, Tanzania, Uganda or Zimbabwe.

## Calibration (held-out test, deciles of predicted probability)

| Decile | Mean predicted | Observed rate | Rows |
|---|---|---|---|
{cal_rows}

Expected calibration error {s['calibration_ece']*100:.3f} percentage points; Brier score {s['brier']:.5f}.

## What drives predictions (mean |TreeSHAP|, 300k-row test sample, log-odds)

| Feature | Mean abs. SHAP |
|---|---|
{shap_rows}

## Reading the numbers honestly

- The gain in *ranking* over the strongest corridor baseline is modest: +3 points of Hit@1 and +2.3 points of Recall@10. Corridors carry most of the signal, and the model's value is in combining them with momentum and artist history.
- The practical gain is in **choosing which songs and markets to work**: 41.2% of Crossfade's weekly top-10 picks came true vs 13.3% for the best baseline, the same 3× gap that PR-AUC (3.6×) shows.
- The large gain is in **PR-AUC (3.6×)**. The model is much better at telling which songs will travel at all, which is what makes its probabilities usable for budgeting.
- The gain is biggest for songs that **debuted in Africa**, where Recall@10 is 93.2% vs 86.1%.
- Coordinated global launches are harder (Recall@5 63.6%) because their remaining markets are often the hard-to-crack ones.
"""
(ROOT / "docs" / "EVALUATION.md").write_text(doc, encoding="utf-8")
print("wrote docs/EVALUATION.md")
